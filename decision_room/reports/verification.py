"""Minimum final verifier: resolve supported references, mark semantic uncertainty.

An arithmetic check alone never certifies attribution in free prose. Only fact
blocks whose labels, units and scopes are generated by a server recipe can carry
verified figures. Adjacent recommendations and causes remain outside that claim.
"""
import hashlib
import re

from ..series import numeric
from . import contract
from .verification_contract import canonical, figure_id, validate

VERSION = 'report-evidence-v4'
TOKEN = re.compile(r'\{\{n:([^{}]+)\}\}')
DIGITS = re.compile(r'(?<!\w)[+−-]?\d+(?:[.,\u00a0 ]\d+)*(?:\s*%)?')


def build(raw, *, resolver=None):
    document, references, issues = contract.load(raw)
    definitions = {}
    ambiguous = set()
    for ref in references:
        if not isinstance(ref, dict) or any(not isinstance(ref.get(k), str) or not ref[k] for k in ('key', 'execution_id', 'metric')):
            issues.append('invalid_number_reference'); continue
        key = ref['key']
        if key in definitions:
            ambiguous.add(key)
        definitions[key] = ref
    resolved = {}
    def resolve(ref):
        if ref['key'] not in resolved:
            resolved[ref['key']] = resolver(ref) if resolver else None
        return resolved[ref['key']]
    certified = {}; fact_slots = {}; fact_operands = {}
    for path, fact, recommendation in contract.fact_entries(document):
        ref = definitions.get(fact['number_key'])
        try:
            check = resolve(ref) if ref and ref['key'] not in ambiguous else None
            display = check.get('display') if check else None
            supported = (check and check.get('origin') in ('deterministic_panorama', 'deterministic_calculation')
                         and check.get('status') in ('verified_in_scope', 'corrected_in_scope')
                         and isinstance(display, dict) and all(isinstance(display.get(k), str) and display[k]
                             for k in ('label', 'scope', 'unit', 'limitation')))
        except Exception:
            supported = False
        if supported:
            label, scope, unit, limitation = (display[k] for k in ('label','scope','unit','limitation'))
            certified[path+'/text'] = display['unit']
        else:
            label, scope, unit, limitation = ('Cifra sin ámbito comprobado',
                'La referencia no permite comprobar conjuntamente cantidad, unidad y alcance.', '', 'No usar como evidencia verificada.')
        prefix = label + ': '
        fact['text'] = prefix + '{{n:' + fact['number_key'] + '}}' + (' '+unit if unit else '') + '. ' + scope + ' ' + limitation
        fact_slots[path+'/text'] = len(prefix)
        if supported and display.get('operands'):
            operands = []
            for operand in display['operands']:
                amount = format(numeric(operand['value']), 'f')
                if '.' in amount:
                    amount = amount.rstrip('0').rstrip('.')
                fact['text'] += ' ' + operand['label'] + ': '
                start = len(fact['text'])
                fact['text'] += amount + ' ' + operand['unit'] + '.'
                operands.append({'span': {'start': start, 'end': start+len(amount)}, 'text': amount,
                                 'value': amount, 'unit': operand['unit']})
            fact_operands[path+'/text'] = operands
    figures = []
    for path, original, recommendation in list(contract.texts(document)):
        output = ''; end = 0; refs = []
        for match in TOKEN.finditer(original):
            # Source category/column names in generated scopes are literal data,
            # even if they contain a template-looking string. Only our value slot resolves.
            if path in fact_slots and match.start() != fact_slots[path]:
                continue
            output += original[end:match.start()]
            start = len(output); visible = match.group(); check = None; ref = definitions.get(match[1])
            if ref and match[1] not in ambiguous and resolver:
                try:
                    check = resolve(ref)
                    if check and check.get('value') is not None:
                        value = numeric(check['value'])
                        decimals = ref.get('decimals', 2)
                        if not value.is_finite() or type(decimals) is not int or not 0 <= decimals <= 8:
                            raise ValueError('Invalid display precision.')
                        visible = format(value, f'.{decimals}f')
                except Exception:
                    check = None
            output += visible; end = match.end()
            corrected = check and check.get('status') == 'corrected_in_scope'
            evidence = []
            if check and check.get('value') is not None:
                evidence = [{'kind': 'observation' if check.get('origin') in ('deterministic_panorama', 'deterministic_calculation') else 'execution',
                             'id': str(ref['execution_id']), 'metric': ref['metric']}]
            verified = bool(path in certified and evidence and check and check.get('status') in ('verified_in_scope', 'corrected_in_scope'))
            refs.append({'path': path, 'span': {'start': start, 'end': len(output)}, 'text': visible,
                         'value': visible if check and check.get('value') is not None else None,
                         'unit': certified[path] if verified else ref.get('unit') if ref and isinstance(ref.get('unit'), str) else None,
                         'status': 'corrected' if corrected else 'verified' if verified else 'unverified' if evidence else 'uncertain',
                         'verified': verified, 'corrected_from': str(check['original_value']) if corrected else None,
                         'evidence': evidence, 'recommendation_id': recommendation})
        output += original[end:]
        contract.set_text(document, path, output)
        if path in fact_operands and refs and refs[0]['verified']:
            # Only the server's value slot was substituted in a fact. Operand
            # offsets move by that one replacement; metadata remains literal.
            offset = len(output)-len(original)
            for operand in fact_operands[path]:
                refs.append({**operand, 'path': path,
                    'span': {k: v+offset for k,v in operand['span'].items()},
                    'status': 'verified', 'verified': True, 'corrected_from': None,
                    'evidence': refs[0]['evidence'], 'recommendation_id': recommendation})
        for match in DIGITS.finditer(output):
            if any(match.start() < f['span']['end'] and f['span']['start'] < match.end() for f in refs):
                continue
            # Locale separators, dates and units are ambiguous without a recipe.
            refs.append({'path': path, 'span': {'start': match.start(), 'end': match.end()}, 'text': match.group(),
                         'value': None, 'unit': None, 'status': 'unverified', 'verified': False,
                         'corrected_from': None, 'evidence': [], 'recommendation_id': recommendation})
        figures.extend(sorted(refs, key=lambda f: f['span']['start']))
    document['verification_annotations'] = [{k: f[k] for k in ('path', 'span', 'text', 'status', 'value', 'unit', 'verified')} for f in figures]
    digest = hashlib.sha256(canonical(document)).hexdigest()
    counts = dict.fromkeys(('verified', 'unverified', 'uncertain', 'corrected'), 0)
    for figure in figures:
        figure['id'] = figure_id(digest, figure['path'], figure['span']['start'], figure['span']['end'])
        counts[figure['status']] += 1
    ledger = {'contract_version': 1, 'draft_sha256': hashlib.sha256(raw).hexdigest(), 'verified_sha256': digest,
              'renderer_version': VERSION, 'figures': figures, 'summary': counts,
              'issues': list(dict.fromkeys([*issues, 'free_prose_not_semantically_verified' if any(f['verified'] for f in figures) else 'semantic_verification_not_available']))}
    validate(ledger, document, raw)
    return document, ledger
